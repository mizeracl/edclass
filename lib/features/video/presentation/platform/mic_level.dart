/// Измеритель уровня звука микрофона, независимый от платформы.
abstract class MicLevelController {
  MicLevelController();

  /// Текущий уровень 0..1. Значение читается по запросу.
  double get level;

  /// true, когда измеритель работает: на web — Web Audio контекст запущен,
  /// на нативных платформах — есть звуковой трек микрофона.
  bool get flowing;

  /// Описание проблемы (нет трека, браузер запретил доступ и т.п.).
  String? get error;

  /// Вызывается по нажатию на плашку теста: на web будит AudioContext
  /// (в некоторых браузерах звук разрешён только после жеста), на нативных
  /// платформах — пустая операция.
  void resume();

  void dispose();
}